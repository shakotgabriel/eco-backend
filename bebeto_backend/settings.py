def _redis_url_for_db(url: str, db: int) -> str:
    """Point a redis/rediss URL at a logical DB, keeping host/TLS/query intact."""
    parts = urlsplit(url)
    return urlunsplit((parts.scheme, parts.netloc, f"/{db}", parts.query, parts.fragment))


